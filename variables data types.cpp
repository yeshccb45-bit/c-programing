#include <iostream>

int main() {
    int x = 10; // integer type
    int y = 20;
    int sum = x + y;

    std::cout << "value of y is: " << y << std::endl;
    std::cout << "value of x is: " << x << std::endl;
    std::cout << "sum is: " << sum << std::endl;


    char grade = 'A'; // character type
    std::cout << "grade is: " << grade << std::endl;    

    std::string name = "John Doe"; // string type   
    std::cout << "name is: " << name << std::endl;

    double pi = 3.14159; // double type
    std::cout << "value of pi is: " << pi << std::endl;

    float e = 2.71828; // float type
    std::cout << "value of e is: " << e << std::endl;

    bool isTrue = true; // boolean type
    std::cout << "isTrue is: " << isTrue << std::endl;

    return 0;
}
